import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

test('independent OFM preview preserves references, source text, layers and exports', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:8011/ofm')
  await expect(page.locator('#status')).toContainText('Local snapshot verified')
  await expect(page.locator('#site-count')).toHaveText('8')
  await expect(page.locator('circle[data-site]')).toHaveCount(8)
  await expect(page.locator('#air-count')).toHaveText('2')
  await expect(page.locator('#airport-count')).toHaveText('1')
  await expect(page.locator('#cycle')).toContainText('Synthetic fixture')
  await page.locator('#features button[data-feature="ase-ctr"]').click()
  await expect(page.locator('#detail')).toContainText('762.000 m in the same reference')
  await expect(page.locator('#detail')).toContainText('above MSL')
  await expect(page.locator('#detail h3')).toContainText('<img src=x')
  expect(await page.evaluate(() => (window as Window & { ofmXss?: number }).ofmXss)).toBeUndefined()
  await page.locator('#type').selectOption('TMA')
  await expect(page.locator('#features button')).toHaveCount(1)
  await page.locator('#features button').click()
  await expect(page.locator('#detail')).toContainText('65 FL')
  await expect(page.locator('#detail')).not.toContainText('6500')
  await page.locator('#type').selectOption('')
  await page.locator('#sites').uncheck()
  await expect(page.locator('circle[data-site]')).toHaveCount(0)
  await page.locator('#sites').check()
  const before = await page.locator('#map').getAttribute('viewBox')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  expect(await page.locator('#map').getAttribute('viewBox')).not.toBe(before)
  await page.getByRole('button', { name: 'Fit region', exact: true }).click()
  await expect(page.locator('#map')).toHaveAttribute('viewBox', '0 0 800 500')
  const download = page.waitForEvent('download')
  await page.locator('#export-air').click()
  const output = await (await download).path()
  const collection = JSON.parse(await readFile(output!, 'utf8'))
  expect(collection.features).toHaveLength(3)
  expect(collection.provenance.source_sha256).toBeTruthy()
  expect(collection.provenance.region.region_id).toBe('hannover-lehrte-5km')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect(errors).toEqual([])
})

test('downloaded OFM preview opens offline with details and no source-script execution', async ({ page, context }, testInfo) => {
  await page.goto('http://127.0.0.1:8011/ofm')
  await expect(page.locator('#status')).toContainText('Local snapshot verified')
  const download = page.waitForEvent('download')
  await page.locator('#export-preview').click()
  const path = testInfo.outputPath('ofm-preview.html')
  await (await download).saveAs(path)
  const text = await readFile(path, 'utf8')
  expect(text).not.toContain('/*OFM_EMBEDDED*/null')
  const offline = await context.newPage()
  const requests: string[] = []
  offline.on('request', request => { if (request.url().startsWith('http')) requests.push(request.url()) })
  await context.setOffline(true)
  try {
    await offline.goto(pathToFileURL(path).href)
    await expect(offline.locator('#status')).toContainText('Local snapshot verified')
    await expect(offline.locator('circle[data-site]')).toHaveCount(8)
    await offline.locator('#features button[data-feature="ase-ctr"]').click()
    await expect(offline.locator('#detail')).toContainText('762.000')
    expect(await offline.evaluate(() => (window as Window & { ofmXss?: number }).ofmXss)).toBeUndefined()
    expect(requests).toEqual([])
  } finally {
    await context.setOffline(false)
  }
})
