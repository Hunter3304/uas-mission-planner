import { expect, test } from '@playwright/test'

test('weighted controls reach the API and export the displayed result without another solve', async ({ page }) => {
  await page.route('https://tile.openstreetmap.org/**', route => route.abort())
  await page.goto('/')
  await page.getByLabel('Saved dataset').selectOption('z-risk-demo')
  await page.getByLabel('Grid cell (m)', { exact: true }).fill('25')
  await page.getByRole('combobox', { name: 'Objective', exact: true }).selectOption('risk')
  await page.getByRole('combobox', { name: 'Algorithm', exact: true }).selectOption('dijkstra')
  await page.getByRole('combobox', { name: 'Objective', exact: true }).selectOption('risk')
  await page.getByLabel('Background score assumption').fill('0')
  await page.getByLabel('Safety distance (m)').fill('2')
  const generate = page.getByRole('button', { name: 'Generate route', exact: true })
  await expect(generate).toBeEnabled()
  let solves = 0
  page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/route')) solves++ })
  const response = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/route'))
  await generate.click()
  const shown = await (await response).json()
  await expect(page.getByTestId('route-result')).toContainText('Route found')
  await expect(page.getByTestId('route-result')).toContainText('exact: true')
  expect(shown.controls.safety_distance_m).toBe(2)
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export route GeoJSON' }).click()
  const stream = await (await event).createReadStream()
  const chunks = []
  for await (const chunk of stream!) chunks.push(chunk)
  const exported = JSON.parse(Buffer.concat(chunks).toString())
  expect(exported.features[0].geometry).toEqual(shown.geometry)
  expect(exported.metadata.runtime_ms).toBe(shown.runtime_ms)
  expect(exported.metadata.controls).toEqual(shown.controls)
  expect(solves).toBe(1)
  await page.getByLabel('Risk weight', { exact: true }).fill('0.8')
  await expect(page.getByTestId('route-result')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Export route GeoJSON' })).toBeDisabled()
})

